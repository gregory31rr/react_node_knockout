/**
 * lib/schema.js — every table Knockout stores, written for PostgreSQL.
 *
 * lib/db.js creates all of this on an empty database the first time the app starts, then runs MIGRATIONS
 * (below) in order. You never run SQL by hand. Without DATABASE_URL the same tables run on SQLite (quick local
 * tries and the browser demo); forSqlite() translates the few words that differ.
 *
 * HOW IT FITS TOGETHER
 *   workspaces      one per manager (or team). Everything else belongs to a workspace, so no one ever sees another's data.
 *   users           everyone who signs in. Each gets their own workspace and a connect code. App owner: platform_role='owner'.
 *   memberships     which workspaces a person belongs to (their own as admin; others' they connected to as member).
 *   connections     requests to connect by code (report / peer / boss); accepting adds each to the other's people.
 *   people          the people you manage or work with (50 reports, your boss, peers). They do NOT need an account.
 *   projects        "GCP migration"… with a short #tag, LOE rollups, and v2 links (parent_id).
 *   items           everything you track: tasks, questions for someone, things to tell someone, asks for updates,
 *                   follow-ups and decisions. Each has an owner (you or a person), priority, LOE hours, due date.
 *   item_events     the history of each item (created, changed, answered, delegated, knocked out, reopened).
 *   links           (paid) a private link for someone outside your team with no account: they see the details, add time
 *                   and notes, and mark it done. You can turn a link off at any time. Your team uses real accounts.
 *   time_logs       time people spent on an item (actual hours, next to the LOE estimate).
 *   invites         account invitations for your team (they set a password and land on their own list).
 *   notifications   in-app notices for people with accounts.
 *   meetings        calls and 1:1s: who was on it, which projects, notes, recording, transcript, summary.
 *   goals           your KPIs and goals (items knocked out, LOE done, on-time %, project done by a date).
 *   sends           every update you sent (summary, delegation, status report) so you have a record.
 *   time_off        PTO, sick days, unplanned absences, holidays (person_id NULL = everyone), training, remote days.
 *                   Capacity and timeline risk subtract time off. PTO balances use people.pto_hours_year.
 *   reminders       your own reminders (once or repeating); they pop up on Today and in notifications when due.
 *   certs           certifications and licenses per person, with expiry dates (warned at 90, 30 and 7 days).
 *   trainings       courses people are taking: target date, % done, hours; training_logs keep each progress update.
 *   notes           your sticky notes (private to you), pinned or tied to a person or project.
 *   audit           append-only activity log.
 *
 * CONVENTIONS
 *   - Dates are text in UTC: 'YYYY-MM-DD' for days, 'YYYY-MM-DD HH:MM:SS' for moments.
 *   - Yes/no columns are 0/1. LOE is hours (DOUBLE PRECISION, e.g. 0.5).
 *   - Date math in SQL uses ko_now(), ko_today(), ko_date('now','-7 days'), ko_datetime(...).
 *
 * TO CHANGE THE SCHEMA LATER: add an entry at the end of MIGRATIONS (never edit an old one).
 */
const FUNCTIONS = `CREATE EXTENSION IF NOT EXISTS citext;
CREATE OR REPLACE FUNCTION ko_ts(base text, m text) RETURNS timestamp LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN m IS NULL OR m = '' THEN b
              WHEN m = 'start of month' THEN date_trunc('month', b)
              WHEN m = 'start of year' THEN date_trunc('year', b)
              WHEN m = 'start of day' THEN date_trunc('day', b)
              ELSE b + m::interval END
  FROM (SELECT CASE WHEN base IS NULL THEN NULL WHEN lower(base) = 'now' THEN (now() AT TIME ZONE 'UTC') ELSE base::timestamp END AS b) x $$;
CREATE OR REPLACE FUNCTION ko_now() RETURNS text LANGUAGE sql STABLE AS $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;
CREATE OR REPLACE FUNCTION ko_today() RETURNS text LANGUAGE sql STABLE AS $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD') $$;
CREATE OR REPLACE FUNCTION ko_date(base text, m text DEFAULT NULL) RETURNS text LANGUAGE sql STABLE AS $$ SELECT to_char(ko_ts(base, m), 'YYYY-MM-DD') $$;
CREATE OR REPLACE FUNCTION ko_datetime(base text, m text DEFAULT NULL) RETURNS text LANGUAGE sql STABLE AS $$ SELECT to_char(ko_ts(base, m), 'YYYY-MM-DD HH24:MI:SS') $$;
CREATE OR REPLACE FUNCTION ko_julianday(base text) RETURNS double precision LANGUAGE sql STABLE AS $$ SELECT extract(epoch FROM ko_ts(base, NULL)) / 86400.0 + 2440587.5 $$;
`;

