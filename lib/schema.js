function forSqlite(ddl) {
  return ddl
    .replace(/BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/g, 'INTEGER PRIMARY KEY')
    .replace(/\bBIGINT\b/g, 'INTEGER').replace(/DOUBLE PRECISION/g, 'REAL').replace(/\bBYTEA\b/g, 'BLOB')
    .replace(/\bCITEXT\b( UNIQUE)?( NOT NULL)?/g, (m, u = '', n = '') => `TEXT${u}${n} COLLATE NOCASE`)
    .replace(/DEFAULT ko_now\(\)/g, 'DEFAULT CURRENT_TIMESTAMP');
}
